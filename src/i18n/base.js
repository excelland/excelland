  function convertTraditional(value) {
    let output = String(value == null ? "" : value);
    output = output.replace(/第\s*(\d+)\s*行/g, "第 $1 橫列");
    output = output.replace(/第\s*(\d+)\s*列/g, "第 $1 欄");
    output = output.replace(/第([一二三四五六七八九十]+)行/g, "第$1橫列");
    output = output.replace(/第([一二三四五六七八九十]+)列/g, "第$1欄");
    output = output.replace(/([A-Z])\s*列/g, "$1 欄");
    output = output.replace(/调整|調整/g, "\uE000");
    output = output.replace(PHRASE_PATTERN, (phrase) => PHRASE_LOOKUP.get(phrase) || phrase);
    output = output.replace(/周(?!怡君)/g, "週");
    return Array.from(output)
      .map((character) => CHAR_MAP[character] || character)
      .join("")
      .replace(/\uE000/g, "調整");
  }

