  function escapeRegExp(value) {
    return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  const ENTITY_PATTERN = new RegExp(
    Array.from(ENTITY_ALIAS_TARGETS.keys())
      .sort((left, right) => right.length - left.length)
      .map((alias) => {
        const escaped = escapeRegExp(alias);
        return /[A-Za-z0-9]/.test(alias)
          ? "(?<![A-Za-z0-9])" + escaped + "(?![A-Za-z0-9])"
          : escaped;
      })
      .join("|"),
    "g"
  );

  function localizeEntities(value, language) {
    const lang = normalizeLanguage(language);
    const source = String(value == null ? "" : value);
    if (lang === "zh-CN") return source;
    const exact = ENTITY_EXACT_TARGETS.get(source.trim());
    if (exact && exact[lang] != null) {
      const leading = (source.match(/^\s*/) || [""])[0];
      const trailing = (source.match(/\s*$/) || [""])[0];
      return leading + exact[lang] + trailing;
    }
    return source.replace(ENTITY_PATTERN, (alias) => {
      const target = ENTITY_ALIAS_TARGETS.get(alias);
      return target && target[lang] != null ? target[lang] : alias;
    });
  }

  function localizeText(value, language) {
    const lang = normalizeLanguage(language);
    const source = String(value == null ? "" : value);
    const localized = localizeEntities(source, lang);
    return lang === "zh-TW" ? convertTraditional(localized) : localized;
  }

